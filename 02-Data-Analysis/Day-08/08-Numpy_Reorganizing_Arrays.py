import numpy as np
#----------------------------------------
print("Reshape matrices:")
before = np.array([[1,2,3,4],[5,6,7,8]])
print(before)
print ("------------------------------")
after = before.reshape((1,8))
print(after)
print ("------------------------------")
after = before.reshape((4,2))
print(after)
print ("------------------------------")
after = before.reshape((2,2,2))
print(after)
print ("------------------------------")
print("Vertically stacking vectors:")
v1 = np.array([1,2,3,4])
v2 = np.array([5,6,7,8])
print ("Array v1:")
print(v1)
print ("Array v2:")
print(v2)
print ("Array v3:")
v3 = np.vstack([v1,v2,v2,v1])
print(v3)
print ("------------------------------")
print("Horizontally stacking vectors:")
h1 = np.ones((2,4))
h2 = np.zeros((2,2))
print ("Array v1:")
print(h1)
print ("Array v2:")
print(h2)
print ("Array v3:")
h3 = np.hstack([h1,h2,h2,h1])
print(h3)
