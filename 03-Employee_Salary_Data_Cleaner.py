import pandas as pd
df = pd.read_csv('Employee_Salary_List.csv')
print ("Dataset:\n",df)
print ("---------------------------------------------")
a = df.isnull()
print ("Finding missing data:\n",a)
print ("---------------------------------------------")
b = df.isnull().sum()
print ("Calculating the number of missing data:\n",b)
print ("---------------------------------------------")
df ["name"]= df["name"].str.strip()
print ("Deleting spaces:\n",df)
print("---------------------------------------------")
df["salary"] = df["salary"].fillna(df["salary"].mean())
print("Dealing with empty salary records:\n", df)
print ("---------------------------------------------")
df = df.drop_duplicates()
print ("Dropping duplicate data:\n",df)
print ("---------------------------------------------")
df.dropna(subset=["name"], inplace=True)
print ("Dropping unnamed records:\n",df)
df.to_csv('Clean_Employee_Salary_List.csv', index=False)
