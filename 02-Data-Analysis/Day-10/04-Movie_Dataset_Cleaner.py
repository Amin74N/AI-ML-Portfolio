import pandas as pd
df = pd.read_csv('Movie_Rating_List.csv')
print ("Dataset:\n",df)
print ("---------------------------------------------")
a = df.isnull()
print ("Finding missing data:\n",a)
print ("---------------------------------------------")
b = df.isnull().sum()
print ("Calculating the number of missing data:\n",b)
print("---------------------------------------------")
df["rating"] = df["rating"].fillna(df["rating"].mean())
print("Dealing with empty salary records:\n", df)
print ("---------------------------------------------")
df = df.drop_duplicates()
print ("Dropping duplicate data:\n",df)
print ("---------------------------------------------")
df.dropna(subset=["movie"], inplace=True)
print ("Dropping unnamed records:\n",df)
df.to_csv('Clean_Movie_Rating_List.csv', index=False)
