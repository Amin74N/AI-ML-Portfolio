import pandas as pd
#--------------------------------------------------------------------
df = pd.read_csv("raw_sales.csv")
#--------------------------------------------------------------------
print(df.isnull().sum())
#--------------------------------------------------------------------
df["age"] = df["age"].fillna(df["age"].mean())
#--------------------------------------------------------------------
df["city"] = df["city"].fillna("Unknown")
#--------------------------------------------------------------------
df.drop_duplicates(inplace=True)
#--------------------------------------------------------------------
df.to_csv("clean_sales.csv",index=False)
