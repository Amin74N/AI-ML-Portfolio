import torch
def main():
    x = torch.randn(2,2, requires_grad= True)
    print("x:\n", x)
    print("--------------------------------------------------------------------------------")
    y = x + 2
    print("y = x + 2:\n", y)
    print("--------------------------------------------------------------------------------")
    z = y * y * 2
    print("z = y * y * 2:\n", z)
    print("--------------------------------------------------------------------------------")
    t = z.mean()
    print("t = z.mean():\n", t)
    print("--------------------------------------------------------------------------------")
    t.backward()
    print("dt/dx:\n", x.grad)
if __name__ == "__main__":
    main()
