import torch
def main():
    x = torch.rand(3,1,1,4)
    print(x)
    print(x.shape)
    print("--------------------------------------------------------------------------------")
    print("Reshape (4*3):")
    y = x.reshape(4,3)
    print(y)
    print(y.shape)
    print("--------------------------------------------------------------------------------")
    print("View (2*6):")
    y = x.view(2,6)
    print(y)
    print(y.shape)
    print("--------------------------------------------------------------------------------")
    print("Flatten (1*12):")
    y = x.flatten()
    print(y)
    print(y.shape)
    print("--------------------------------------------------------------------------------")
    print("Squeeze (Deleting dimensions with size=1):")
    y = x.squeeze()
    print(y)
    print(y.shape)
    print("--------------------------------------------------------------------------------")
    print("Unsqueeze (Adding a dimension with size=1 as the 5th dimension):")
    y = x.unsqueeze(4)
    print(y)
    print(y.shape)
if __name__ == "__main__":
    main()
