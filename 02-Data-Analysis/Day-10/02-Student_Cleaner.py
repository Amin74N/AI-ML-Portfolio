import pandas as pd
data = {"name": [" Ali ","Sara",None,"Ali"],"score": [18,None,17,18]}
df = pd.DataFrame(data)
print ("Dataset:\n",df)
print ("---------------------------------------------")
a = df.isnull()
print ("Finding missing data:\n",a)
print ("---------------------------------------------")
b = df.isnull().sum()
print ("Calculating the number of missing data:\n",b)
print ("---------------------------------------------")
df ["name"]= df["name"].str.strip()
print ("Deleting spaces:\n",df)
print ("---------------------------------------------")
df = df.drop_duplicates()
print ("Dropping duplicate data:\n",df)
print ("---------------------------------------------")
df["score"] = df["score"].fillna(df["score"].mean())
print ("Dealing with empty score records:\n",df)
print ("---------------------------------------------")
df.dropna(subset=["name"], inplace=True)
print ("Dropping unnamed records:\n",df)
