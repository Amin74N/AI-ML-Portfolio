import torch
def main():
    print("X and Y:")
    x = torch.tensor([[1,2],[4,3]])
    y = torch.tensor([[3,4],[1,2]])
    print(x)
    print(y)
    print("--------------------------------------------------------------------------------")
    print("Addition:")
    z = x + y   # Equivalent to torch.add(x, y)
    print(z)
    print("--------------------------------------------------------------------------------")
    print("Subtraction:")
    z = x - y   # Equivalent to torch.sub(x, y)
    print(z)
    print("--------------------------------------------------------------------------------")
    print("Multiplication:")
    z = x * y   # Equivalent to torch.mul(x, y)
    print(z)
    print("--------------------------------------------------------------------------------")
    print("Matrix Multiplication:")
    z = x @ y   # Equivalent to torch.matmul(x,y)
    print(z)
    print("--------------------------------------------------------------------------------")
    print("Division:")
    z = x / y   # Equivalent to torch.div(x, y)
    print(z)
if __name__ == "__main__":
    main()
