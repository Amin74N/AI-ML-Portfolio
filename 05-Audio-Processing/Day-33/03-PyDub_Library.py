from pydub import AudioSegment
# ----------------------------------------------------------------------------------------------------------------------
# Reading a WAV audio file:
input_audio = AudioSegment.from_wav("audio/input.wav")
input_audio2 = AudioSegment.from_wav("audio/input.wav")
# ----------------------------------------------------------------------------------------------------------------------
# Increasing the volume by 6dB:
louder = input_audio + 6
# ----------------------------------------------------------------------------------------------------------------------
# Decreasing the volume by 6dB:
quieter = input_audio - 6
# ----------------------------------------------------------------------------------------------------------------------
# Repeating the audio file:
repeated = input_audio * 2
# ----------------------------------------------------------------------------------------------------------------------
# Trimming the audio:
trim = input_audio[10000:15000]
# ----------------------------------------------------------------------------------------------------------------------
# Merging 2 audio files:
merged = input_audio + input_audio2
# ----------------------------------------------------------------------------------------------------------------------
# Fade-in by 2s:
fade_in = input_audio.fade_in(2000)
# ----------------------------------------------------------------------------------------------------------------------
# Fade-out by 2s:
fade_out = input_audio.fade_out(2000)
# ----------------------------------------------------------------------------------------------------------------------
# Changing the format:
input_audio.export("audio/pydub_output.mp3", format="mp3")
